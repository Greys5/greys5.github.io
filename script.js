let memeTimer;

function dismissMeme() {
  clearTimeout(memeTimer);
  if (memePopup.contains(document.activeElement)) {
    languageSwitch.focus({ preventScroll: true });
  }
  memePopup.hidden = true;
}

function showLatinoMeme() {
  clearTimeout(memeTimer);
  memePopup.hidden = false;
  const anchor = languageSwitch.getBoundingClientRect();
  const left = Math.max(12, Math.min(anchor.right - memePopup.offsetWidth, window.innerWidth - memePopup.offsetWidth - 12));
  const top = Math.max(12, Math.min(anchor.bottom + 12, window.innerHeight - memePopup.offsetHeight - 12));
  memePopup.style.left = `${left}px`;
  memePopup.style.top = `${top}px`;
  memeTimer = setTimeout(dismissMeme, 3500);
}

dismissMemeButton.addEventListener('click', dismissMeme);
document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape' && !memePopup.hidden) dismissMeme();
});
window.addEventListener('resize', dismissMeme);


function setLanguage(nextLanguage) {
  language = nextLanguage === 'es' ? 'es' : 'en';
  document.documentElement.lang = language;
  document.title = metadata[language].title;
  document.querySelector('meta[name="description"]').content = metadata[language].description;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = translations[element.dataset.i18n][language];
  });
  document.querySelectorAll('[data-i18n-attr]').forEach((element) => {
    const entry = translatedAttributes[element.dataset.i18nAttr];
    element.setAttribute(entry.attr, entry[language]);
  });
  question.textContent = questions[language][questionIndex];
  languageSwitch.setAttribute('aria-pressed', String(language === 'es'));
  languageSwitch.setAttribute('aria-label', metadata[language].switchLabel);
  languageSwitch.dataset.language = language;
  const targetLabel = languageSwitch.querySelector('.language-target');
  targetLabel.textContent = metadata[language].targetLabel;
  targetLabel.lang = metadata[language].targetLanguage;
}

nextQuestion.addEventListener('click', () => {
  questionIndex = (questionIndex + 1) % questions[language].length;
  question.textContent = questions[language][questionIndex];
});
